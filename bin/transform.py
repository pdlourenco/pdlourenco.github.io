def map_experience(entries: list[dict]) -> list[dict]:
    out = []
    for e in sorted(entries, key=_sort_key_chronological):
        out.append(
            _compact(
                {
                    "company": val(e, "organization"),
                    "position": val(e, "position"),
                    "location": val(e, "location"),
                    "start_date": val(e, "start"),
                    "end_date": end_date(e),
                    "summary": val(e, "description"),
                }
            )
        )
    return out


def map_education(entries: list[dict]) -> list[dict]:
    out = []
    for e in sorted(entries, key=_sort_key_chronological):
        universities = val(e, "university") or []
        school = val(e, "school")
        institution = school or " / ".join(universities)
        highlights = []
        if school and universities:
            highlights.append(f"{', '.join(universities)}")
        if val(e, "institute"):
            highlights.append(f"{e['institute']}")
        if val(e, "thesis_title"):
            highlights.append(f"Thesis: *{e['thesis_title']}*")
        advisors = val(e, "advisors")
        if advisors:
            label = "Advisor" if len(advisors) == 1 else "Advisors"
            highlights.append(f"{label}: {', '.join(advisors)}")
        for key, label in (("grade", "Grade"), ("grant", "Grant"), ("award", "Award")):
            if val(e, key):
                highlights.append(f"{label}: {e[key]}")
        out.append(
            _compact(
                {
                    "institution": institution,
                    "area": val(e, "field"),
                    # `degree` is RenderCV's key; the gem reads it too (SCHEMA-NOTES §1).
                    "degree": val(e, "degree"),
                    "start_date": val(e, "start"),
                    "end_date": end_date(e),
                    "courses": val(e, "courses"),
                    "highlights": highlights or None,
                }
            )
        )
    return out


def map_projects(entries: list[dict]) -> list[dict]:
    def key(e: dict) -> tuple:
        importance = val(e, "importance")
        return (importance if importance is not None else 10**6, str(val(e, "name") or ""))

    out = []
    for e in sorted(entries, key=key):
        highlights = []
        if val(e, "keywords"):
            highlights.append(f"Keywords: {e['keywords']}")
        if val(e, "code"):
            highlights.append(f"Code: <{e['code']}>")
        out.append(
            _compact(
                {
                    "name": val(e, "name"),
                    "start_date": val(e, "start"),
                    "end_date": end_date(e),
                    "summary": val(e, "description"),
                    "url": val(e, "url"),
                    "highlights": highlights or None,
                }
            )
        )
    return out


def map_awards(entries: list[dict]) -> list[dict]:
    out = []
    for e in sorted(entries, key=lambda e: (_neg_date(val(e, "date")), str(val(e, "title") or ""))):
        out.append(
            _compact(
                {
                    # `name` anchors the entry to RenderCV's NormalEntry so it validates;
                    # `title`/`awarder` are what the gem's awards.liquid actually renders.
                    # Emitting both satisfies each contract — SCHEMA-NOTES.md §1.
                    "name": val(e, "title"),
                    "title": val(e, "title"),
                    "awarder": val(e, "awarder"),
                    "date": val(e, "date"),
                    "summary": val(e, "description"),
                }
            )
        )
    return out


def map_skills(entries: list[dict]) -> list[dict]:
    """One entry per group, skills ordered by level then name.

    The gem's skills.liquid renders `name` + `keywords`, which reads far better as
    "Programming: Python, JavaScript" than as one card per skill. `level` is not
    displayed by that template, so it is used as the ordering key rather than dropped.
    """
    groups: dict[str, list[dict]] = {}
    for e in entries:
        groups.setdefault(val(e, "group") or "Other", []).append(e)
    out = []
    for group in sorted(groups):
        members = sorted(
            groups[group],
            key=lambda e: (-(val(e, "level") or 0), str(val(e, "name") or "")),
        )
        out.append(
            _compact(
                {
                    "name": group,
                    "keywords": ", ".join(str(val(m, "name")) for m in members),
                }
            )
        )
    return out


def map_languages(entries: list[dict]) -> list[dict]:
    out = []
    for e in sorted(entries, key=lambda e: (not e.get("mother_tongue"), str(val(e, "name") or ""))):
        if e.get("mother_tongue"):
            summary = "Mother tongue"
        else:
            summary = _bullet_lines(
                *[
                    f"{label} {val(e, key)}"
                    for key, label in (
                        ("speaking", "Speaking"),
                        ("understanding", "Understanding"),
                        ("writing", "Writing"),
                    )
                    if val(e, key) is not None
                ]
            ) or None
        out.append(_compact({"name": val(e, "name"), "summary": summary}))
    return out


def map_research_interests(entries: list[dict]) -> list[dict]:
    """Grouped, and emitted under `Academic Interests` so the gem's richer template runs.

    `Research Interests` is NOT special-cased by al_folio_cv; `Academic Interests` is
    (D14). Same content, a template instead of the bare fallback.
    """
    groups: dict[str, list[dict]] = {}
    for e in entries:
        groups.setdefault(val(e, "group") or "Other", []).append(e)
    out = []
    for group in sorted(groups):
        members = sorted(
            groups[group], key=lambda e: (-(val(e, "level") or 0), str(val(e, "name") or ""))
        )
        out.append(
            _compact(
                {
                    "name": group,
                    "keywords": ", ".join(str(val(m, "name")) for m in members),
                }
            )
        )
    return out


def _student_bullet(e: dict, with_role: bool = False) -> str:
    """A student as one markdown bullet.

    Custom sections reach al_folio_cv's generic branch, which renders `bullet` and
    nothing else (D14) — so the structure has to live in the text.
    """
    head = f"**{val(e, 'name')}**"
    degree = val(e, "thesis_type") or val(e, "degree")
    thesis = f"*{e['thesis_title']}*" if val(e, "thesis_title") else None
    universities = ", ".join(val(e, "university") or []) or None
    supervisors = val(e, "supervisors")
    span = "–".join(x for x in (val(e, "start"), val(e, "end") or "present") if x)
    tail = _bullet_lines(
        degree,
        thesis,
        universities,
        f"with {', '.join(supervisors)}" if supervisors else None,
        span or None,
        val(e, "jury_role") if with_role else None,
        f"Grade: {e['grade']}" if val(e, "grade") else None,
        val(e, "award"),
        f"now {e['current_position']}" if val(e, "current_position") else None,
    )
    return f"{head} — {tail}" if tail else head


def map_students(entries: list[dict], with_role: bool = False) -> list[dict]:
    ordered = sorted(entries, key=_sort_key_chronological)
    return [{"bullet": _student_bullet(e, with_role=with_role)} for e in ordered]


#: intermediate section -> (al-folio section title, mapper). The title choices are
#: load-bearing: see SPECIAL_CASED_SECTIONS and D14.
CV_SECTION_MAP: dict[str, tuple[str, Any]] = {
    "experience": ("Experience", map_experience),
    "education": ("Education", map_education),
    "projects": ("Projects", map_projects),
    "awards": ("Awards", map_awards),
    "skills": ("Skills", map_skills),
    "languages": ("Languages", map_languages),
    "research_interests": ("Academic Interests", map_research_interests),
    # `teaching` is a mapping, not a list, and expands into two sections — handled below.
    "teaching": ("", None),
}

#: Order sections appear on the page. Experience is hoisted by the gem regardless.
SECTION_ORDER = [
    "Experience",
    "Education",
    "Projects",
    "Supervised Students",
    "Jury",
    "Awards",
    "Skills",
    "Academic Interests",
    "Languages",
]


def _compact(mapping: dict) -> dict:
    """Drop absent keys. An absent field must not become an empty string in the output."""
    return {k: v for k, v in mapping.items() if v is not None}


def build_cv(cv_in: dict, profile: dict) -> dict:
    unknown = sorted(set(cv_in) - set(CV_SECTION_MAP))
    if unknown:
        raise TransformError(
            "cv.yml has top-level section(s) this transform has no mapping for.",
            [f"unmapped section: {u!r}" for u in unknown]
            + [
                "The schema tolerates new sections on purpose (forward-compatibility), so",
                "the transform is where this has to be loud — otherwise the content would",
                "simply not appear on the site. Add a mapping in CV_SECTION_MAP, or remove",
                "the section from the graph. See docs/intermediate-schema/README.md.",
            ],
        )

    sections: dict[str, list[dict]] = {}
    for key, (title, mapper) in CV_SECTION_MAP.items():
        if key not in cv_in:
            continue
        if key == "teaching":
            teaching = cv_in["teaching"] or {}
            if teaching.get("supervised_students"):
                sections["Supervised Students"] = map_students(teaching["supervised_students"])
            if teaching.get("jury"):
                sections["Jury"] = map_students(teaching["jury"], with_role=True)
            continue
        entries = cv_in[key] or []
        if entries:
            sections[title] = mapper(entries)

    _assert_renderable(sections)

    ordered = {t: sections[t] for t in SECTION_ORDER if t in sections}
    # Any section not in SECTION_ORDER would silently vanish here, so assert instead.
    missed = sorted(set(sections) - set(ordered))
    if missed:  # pragma: no cover - guards a future mapping added without an order entry
        raise TransformError(
            "section(s) were built but have no place in SECTION_ORDER.",
            [f"{m!r} would not be emitted" for m in missed],
        )

    header = _compact(
        {
            "name": val(profile, "name_long"),
            "email": val(profile, "email_personal"),
            "website": (val(profile, "web") or {}).get("url"),
            "summary": val(profile, "bio_long") or val(profile, "bio_short"),
        }
    )
    return {"cv": {**header, "sections": ordered}}


def _assert_renderable(sections: dict[str, list[dict]]) -> None:
    """Every entry in a non-special-cased section must render (D14).

    al_folio_cv's generic branch emits only `bullet` or `label`+`details`. An entry with
    any other shape produces an empty card with no warning, so this is checked here
    rather than discovered on the rendered page.
    """
    problems = []
    for title, entries in sections.items():
        if title in SPECIAL_CASED_SECTIONS:
            continue
        for i, entry in enumerate(entries):
            if "bullet" in entry or ("label" in entry and "details" in entry):
                continue
            problems.append(
                f"{title}[{i}]: keys {sorted(entry)} render as an empty card — a section "
                "al_folio_cv does not special-case must use `bullet` or `label`+`details`"
            )
    if problems:
        raise TransformError("generated CV contains entries the site cannot render.", problems)


