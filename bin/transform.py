def _load(path: pathlib.Path) -> Any:
    text = path.read_text(encoding="utf-8")
    if path.suffix == ".json":
        return json.loads(text)
    return yaml.safe_load(text) or {}


def _validate(name: str, data: Any) -> list[str]:
    schema = json.loads((SCHEMAS / SCHEMA_FOR[name]).read_text(encoding="utf-8"))
    validator = Draft202012Validator(schema)
    problems = []
    for err in sorted(validator.iter_errors(data), key=str):
        where = "/".join(str(p) for p in err.absolute_path) or "(root)"
        problems.append(f"{name}: {where}: {err.message}")
    return problems


def read_incoming(incoming: pathlib.Path) -> dict[str, Any]:
    """Load, validate and version-gate the staged export. Raises TransformError."""
    manifest_path = incoming / "manifest.json"
    if not manifest_path.exists():
        raise TransformError(
            f"{incoming}/manifest.json is missing, so the export cannot be verified.",
            [
                "Copy the plugin's whole export directory, not just the YAML files.",
                "The plugin's sync.sh currently writes to _data/ and _posts/ instead of",
                "_incoming/ — see docs/DECISIONS.md D21. Copy by hand until that is fixed.",
            ],
        )

    manifest = _load(manifest_path)
    problems = _validate("manifest.json", manifest)

    version = manifest.get("schema_version")
    if version is None:
        raise TransformError(
            "the export declares no schema_version, so its shape cannot be trusted.",
            [
                "This is what today's plugin emits; it is a known gap, not your mistake.",
                "Tracked as pdlourenco/logseq-alfolio-export#1 (see docs/DECISIONS.md D29).",
                f"This transform understands version(s): {sorted(SUPPORTED_SCHEMA_VERSIONS)}.",
            ],
        )
    if version not in SUPPORTED_SCHEMA_VERSIONS:
        raise TransformError(
            f"the export declares schema_version {version!r}, which this transform does not know.",
            [
                f"Understood version(s): {sorted(SUPPORTED_SCHEMA_VERSIONS)}.",
                "Refusing rather than guessing: an unknown shape loses content silently.",
                "Update bin/transform.py and docs/intermediate-schema/ together.",
            ],
        )

    problems += _check_export_integrity(incoming, manifest)

    data: dict[str, Any] = {"manifest": manifest}
    for name in ("cv.yml", "profile.yml", "personal.yml", "publication_overrides.yml"):
        path = incoming / name
        if not path.exists():
            continue
        try:
            loaded = _load(path)
        except (yaml.YAMLError, json.JSONDecodeError) as exc:
            problems.append(f"{name}: unparseable — {exc}")
            continue
        problems += _validate(name, loaded)
        data[name] = loaded

    bib_path = incoming / "papers.src.bib"
    if bib_path.exists():
        data["papers.src.bib"] = bib_path.read_text(encoding="utf-8")

    if problems:
        raise TransformError(
            f"the staged export in {incoming} does not match the contract in "
            "docs/intermediate-schema/ (contract v1).",
            problems,
        )
    return data


def _check_export_integrity(incoming: pathlib.Path, manifest: dict) -> list[str]:
    """Files listed vs files present, both ways, plus hashes — catches a partial copy."""
    problems: list[str] = []
    listed = set(manifest.get("files") or [])
    present = {
        str(p.relative_to(incoming))
        for p in incoming.rglob("*")
        if p.is_file() and p.name not in MANIFEST_EXEMPT
    }
    for missing in sorted(listed - present):
        problems.append(f"manifest lists {missing!r} but it is not in {incoming}/")
    for extra in sorted(present - listed):
        problems.append(f"{extra!r} is in {incoming}/ but not listed in the manifest")
    for name, expected in sorted((manifest.get("hashes") or {}).items()):
        target = incoming / name
        if not target.exists():
            problems.append(f"manifest hashes {name!r} but the file is missing")
            continue
        actual = hashlib.sha256(target.read_bytes()).hexdigest()
        if actual != expected:
            problems.append(
                f"{name}: sha256 mismatch — the copy is incomplete or the file was edited "
                f"(manifest {expected[:12]}…, file {actual[:12]}…)"
            )
    return problems


