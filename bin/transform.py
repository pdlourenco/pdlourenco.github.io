#!/usr/bin/env python3
"""Transform the staged Logseq export in _incoming/ into al-folio's data formats.

    bin/transform.py            # write generated files
    bin/transform.py --check    # verify committed output matches _incoming/ (CI)

Contract (docs/IMPLEMENTATION-PLAN.md, docs/DECISIONS.md):

* **Idempotent.** Running twice produces byte-identical output. Nothing time-dependent
  reaches a generated file — `manifest.exported_at` is deliberately ignored (P5/D29).
* **Fails loudly.** Schema violations, unknown contract versions, unmapped sections and
  entry shapes the site cannot render are errors with actionable messages, never warnings
  that produce half-empty YAML.
* **Owns what it marks.** Generated files carry GENERATED_HEADER; files without it are
  never touched, and generated files whose source disappeared are pruned (P6).
* **Never invents.** Absent input yields an absent key, not a placeholder.

Phase 3 maps `cv.yml` → `_data/cv.yml` and `profile.yml` → `_data/socials.yml`.
`personal.yml` (Phase 5) and `publication_overrides.yml` (Phase 4) are validated and
explicitly reported as not-yet-consumed rather than silently ignored.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import pathlib
import sys
from typing import Any

import yaml
from jsonschema import Draft202012Validator

# `bin/` is not a package; make the sibling module importable however this is invoked.
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import bibliography as bib  # noqa: E402  (needs the path insert above)

REPO = pathlib.Path(__file__).resolve().parent.parent
SCHEMAS = REPO / "docs" / "intermediate-schema"

GENERATED_HEADER = "# GENERATED by bin/transform.py from _incoming/ — do not edit by hand"

#: The same marker in BibTeX comment syntax. `_is_ours()` accepts either, so ownership and
#: pruning work identically for `_bibliography/papers.bib`.
GENERATED_HEADER_BIB = GENERATED_HEADER.replace("#", "%", 1)

#: Contract versions this transform understands. Refusing an unknown version is the point
#: of the gate: guessing at a shape we have not seen is how content vanishes silently.
SUPPORTED_SCHEMA_VERSIONS = frozenset({1})

SCHEMA_FOR = {
    "cv.yml": "cv.schema.json",
    "profile.yml": "profile.schema.json",
    "personal.yml": "personal.schema.json",
    "publication_overrides.yml": "publication_overrides.schema.json",
    "manifest.json": "manifest.schema.json",
}

#: Files the contract defines but this phase does not consume yet, and what will.
NOT_YET_CONSUMED = {"personal.yml": "Phase 5"}

#: Files allowed in _incoming/ without appearing in the plugin's manifest. `README.md` is
#: ours; `papers.src.bib` is exported from Zotero by hand and the plugin knows nothing about
#: it (D49). Kept deliberately narrow so a plugin that later emits a bibliography still
#: round-trips through the integrity check.
MANIFEST_EXEMPT = frozenset({"README.md", "papers.src.bib"})

#: Section titles al_folio_cv special-cases. Anything else falls to its generic branch,
#: which renders ONLY `bullet` or `label`+`details` (docs/SCHEMA-NOTES.md §1, D14).
SPECIAL_CASED_SECTIONS = frozenset(
    {
        "Experience", "Volunteer", "Education", "Awards", "Honors and Awards",
        "Publications", "Skills", "Languages", "Interests", "Academic Interests",
        "Certificates", "Projects", "Open Source Projects", "References",
    }
)


class TransformError(Exception):
    """A failure the operator must fix. Carries every problem found, not just the first."""

    def __init__(self, summary: str, problems: list[str] | None = None):
        self.summary = summary
        self.problems = problems or []
        super().__init__(summary)

    def render(self) -> str:
        lines = [f"error: {self.summary}"]
        lines += [f"    {p}" for p in self.problems]
        return "\n".join(lines)


