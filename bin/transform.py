#: A file whose presence means an export has been staged. A directory holding only a
#: README is "not staged"; a directory holding cv.yml but no manifest is a partial copy,
#: which must fail rather than be treated as empty.
EXPORT_MARKERS = ("manifest.json", "cv.yml", "profile.yml", "personal.yml",
                  "publication_overrides.yml", "papers.src.bib", "blog")


def is_staged(incoming: pathlib.Path) -> bool:
    return incoming.exists() and any((incoming / name).exists() for name in EXPORT_MARKERS)


def run(incoming: pathlib.Path, repo: pathlib.Path, check: bool) -> int:
    if not is_staged(incoming):
        shown = incoming.relative_to(repo) if incoming.is_relative_to(repo) else incoming
        # Header-marked files are evidence that an export existed. Their source is now
        # gone, so they are orphans (P6) — the one case where this path must be loud
        # rather than a clean no-op.
        orphans = prune(set(), [repo / "_data"], repo, check)
        if orphans:
            if check:
                raise TransformError(
                    f"{shown} holds no export, but generated files are still committed.",
                    [f"sourceless: {o}" for o in orphans]
                    + ["Restore the export, or run bin/transform.py to prune them (D4/P6)."],
                )
            for o in orphans:
                print(f"pruned {o} (no export staged)")
            return 0
        print(
            f"nothing staged: {shown} holds no export, so there is nothing to transform.\n"
            "  This is the expected state until a Logseq export is copied in; see\n"
            "  _incoming/README.md. A directory with export files but no manifest.json is a\n"
            "  partial copy and does fail — that is not this case."
        )
        return 0

    data = read_incoming(incoming)
    profile = data.get("profile.yml", {})

    outputs: dict[pathlib.Path, str] = {}
    if "cv.yml" in data:
        outputs[repo / "_data" / "cv.yml"] = serialize(
            build_cv(data["cv.yml"], profile), "_incoming/cv.yml + _incoming/profile.yml"
        )
    if profile:
        outputs[repo / "_data" / "socials.yml"] = serialize(
            build_socials(profile), "_incoming/profile.yml"
        )
    if "papers.src.bib" in data:
        outputs[repo / "_bibliography" / "papers.bib"] = build_bibliography(data, repo)

    changed, refused = write_outputs(outputs, repo, check)
    pruned = prune(set(outputs), [repo / "_data", repo / "_bibliography"], repo, check)

    for name, phase in NOT_YET_CONSUMED.items():
        if name in data:
            print(f"note: {name} validated but not consumed yet — {phase} maps it.")

    if refused:
        raise TransformError("refused to write over files this transform does not own.", refused)

    if check:
        if changed or pruned:
            raise TransformError(
                "committed output is out of date with _incoming/.",
                [f"would rewrite: {c}" for c in changed]
                + [f"would prune: {p}" for p in pruned]
                + ["Run bin/transform.py and commit the result (docs/DECISIONS.md D4)."],
            )
        print(f"up to date: {len(outputs)} generated file(s) match _incoming/")
        return 0

    for c in changed:
        print(f"wrote {c}")
    for p in pruned:
        print(f"pruned {p} (source gone)")
    if not changed and not pruned:
        print(f"up to date: {len(outputs)} generated file(s) already match _incoming/")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true",
        help="verify committed output matches _incoming/; write nothing (exit 1 if stale)",
    )
    parser.add_argument("--incoming", type=pathlib.Path, default=None,
                        help="staged export directory (default: <repo>/_incoming)")
    parser.add_argument("--repo", type=pathlib.Path, default=REPO,
                        help="repository root to write into (default: this checkout)")
    args = parser.parse_args(argv)
    repo = args.repo.resolve()
    incoming = (args.incoming or repo / "_incoming").resolve()

    try:
        return run(incoming, repo, args.check)
    except TransformError as exc:
        print(exc.render(), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
