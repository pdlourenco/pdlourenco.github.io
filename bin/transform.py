# Deterministic serialization, writing, pruning
# ---------------------------------------------------------------------------------------


class _Dumper(yaml.SafeDumper):
    """Block style, stable indentation — pinned so --check compares like with like (P5)."""

    def increase_indent(self, flow=False, indentless=False):  # noqa: D102
        return super().increase_indent(flow, False)


def serialize(data: dict, source_note: str) -> str:
    body = yaml.dump(
        data,
        Dumper=_Dumper,
        sort_keys=False,          # mapping order is meaningful: it is display order
        allow_unicode=True,       # "Lourenço", not "Louren\xE7o"
        default_flow_style=False,
        width=100,
    )
    return f"{GENERATED_HEADER}\n# source: {source_note}\n{body}"


def _is_ours(path: pathlib.Path) -> bool:
    if not path.exists():
        return False
    with io.open(path, encoding="utf-8") as fh:
        return fh.readline().strip() in (GENERATED_HEADER, GENERATED_HEADER_BIB)


def write_outputs(
    outputs: dict[pathlib.Path, str], repo: pathlib.Path, check: bool
) -> tuple[list[str], list[str]]:
    """Write (or verify) generated files. Returns (changed, refused)."""
    changed, refused = [], []
    for path, content in sorted(outputs.items()):
        rel = path.relative_to(repo)
        if path.exists() and not _is_ours(path):
            refused.append(
                f"{rel} exists without the generated header — refusing to overwrite "
                "hand-written content. Move it aside if the transform should own it."
            )
            continue
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        changed.append(str(rel))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    return changed, refused


def prune(owned: set[pathlib.Path], roots: list[pathlib.Path], repo: pathlib.Path,
          check: bool) -> list[str]:
    """Remove generated files whose source disappeared (P6); never touch other files."""
    pruned = []
    for root in roots:
        if not root.exists():
            continue
        for path in sorted(root.rglob("*")):
            if not path.is_file() or path in owned or not _is_ours(path):
                continue
            pruned.append(str(path.relative_to(repo)))
            if not check:
                path.unlink()
    return pruned


