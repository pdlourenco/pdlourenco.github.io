def build_bibliography(data: dict, repo: pathlib.Path) -> str:
    """Generated bibliography text, including its ownership header.

    The owner's name comes from `_config.yml`'s `scholar.last_name`/`first_name`, which is
    also what `bib.liquid` uses to italicise his own name — so authorship (D43) and
    self-highlighting can never disagree about who he is.
    """
    surname, forenames = _scholar_identity(repo)
    assets = frozenset(p.name for p in (repo / "assets" / "pdf").glob("*.pdf"))
    try:
        body, notes = bib.build(
            data["papers.src.bib"],
            data.get("publication_overrides.yml"),
            surname,
            forenames,
            assets,
        )
    except bib.BibError as exc:
        raise TransformError(exc.summary, exc.problems) from exc
    for note in notes:
        print(f"note: {note}")
    source = "_incoming/papers.src.bib"
    if data.get("publication_overrides.yml"):
        source += " + _incoming/publication_overrides.yml"
    return f"{GENERATED_HEADER_BIB}\n% source: {source}\n\n{body}"


def _scholar_identity(repo: pathlib.Path) -> tuple[str, list[str]]:
    config = yaml.safe_load((repo / "_config.yml").read_text(encoding="utf-8")) or {}
    scholar = config.get("scholar") or {}
    last = scholar.get("last_name")
    first = scholar.get("first_name")
    last = last if isinstance(last, list) else [last]
    first = first if isinstance(first, list) else [first]
    last = [x for x in last if x]
    if not last:
        raise TransformError(
            "_config.yml has no scholar.last_name, so the bibliography cannot tell which "
            "entries are the owner's.",
            ["Set scholar.last_name and scholar.first_name; D43 keys authorship off them."],
        )
    return last[0], [x for x in first if x]


